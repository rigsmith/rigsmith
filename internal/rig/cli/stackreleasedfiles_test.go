func stackReleaseFileFixture(t *testing.T, git bool) string {
	t.Helper()
	root := t.TempDir()
	if git {
		mustGitStack(t, root, "init", "-q", "-b", "main")
	}
	return root
}

func stackReleaseFileWrite(t *testing.T, root, path, body string) string {
	t.Helper()
	path = filepath.Join(root, path)
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0644); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestStackReleasedProjectDirectories(t *testing.T) {
	for _, git := range []bool{false, true} {
		t.Run(map[bool]string{false: "snapshot", true: "git"}[git], func(t *testing.T) {
			for _, dir := range []string{"packages", "generated", "vendor"} {
				t.Run(dir, func(t *testing.T) {
					root := stackReleaseFileFixture(t, git)
					member := filepath.Join(root, "app")
					project := stackReleaseFileWrite(t, member, dir+"/App/App.csproj", `<Project><ItemGroup><PackageReference Include="You.Lib" Version="2.0.0-edge.1" /></ItemGroup></Project>`)
					guard := stackReleaseFileWrite(t, member, dir+"/App/Code.cs", "#if STACK_YOU_LIB\nApi.New();\n#else\nApi.Old();\n#endif\n")
					// One tracked source and one non-ignored untracked source exercise both
					// halves of ls-files; the snapshot uses its filesystem fallback.
					if git {
						mustGitStack(t, root, "add", "--", project)
					}
					selection := stackReleaseSelection{Reference: "You.Lib", Original: "Lib"}
					edits, _, err := stackReleaseSelectedEdits(member, selection, "Lib", "2.0.0")
					if err != nil {
						t.Fatal(err)
					}
					if err = stackReleaseWrite(edits); err != nil {
						t.Fatal(err)
					}
					data, err := os.ReadFile(project)
					if err != nil || !bytes.Contains(data, []byte(`Include="Lib" Version="2.0.0"`)) {
						t.Fatalf("project=%s err=%v", data, err)
					}
					data, err = os.ReadFile(guard)
					if err != nil || string(data) != "Api.New();\n" {
						t.Fatalf("guard=%s err=%v", data, err)
					}
					already, err := stackReleasedAlready(member, "Lib", "2.0.0")
					if err != nil || !already {
						t.Fatalf("already=%v err=%v", already, err)
					}
					// Restore a source reference but mark this file unsupported by the editor.
					// The identity check must still see it and refuse the entire plan.
					stackReleaseFileWrite(t, member, dir+"/App/App.csproj", `<Project><ItemGroup><PackageReference Include="You.Lib" Version="2.0.0-edge.1" /></ItemGroup></Project>`)
					stackReleaseFileWrite(t, member, dir+"/App/Leftover.csproj", `<Project><!-- <auto-generated --> <ItemGroup><PackageReference Include="You.Lib" Version="2.0.0-edge.1" /></ItemGroup></Project>`)
					edits, _, err = stackReleaseSelectedEdits(member, selection, "Lib", "2.0.0")
					if err == nil || !strings.Contains(err.Error(), "all-or-nothing") || !strings.Contains(err.Error(), "You.Lib") || len(edits) != 0 {
						t.Fatalf("leftover accepted: edits=%v err=%v", edits, err)
					}
					ids, err := stackReleaseReferenceIDs(member, nil)
					if err != nil || !slices.Contains(ids, "You.Lib") {
						t.Fatalf("missing leftover: %v %v", ids, err)
					}
				})
			}
		})
	}
}

func TestStackReleasedIgnoredPackages(t *testing.T) {
	root := stackReleaseFileFixture(t, true)
	member := filepath.Join(root, "app")
	stackReleaseFileWrite(t, root, ".gitignore", "packages/\n")
	stackReleaseFileWrite(t, member, "App.csproj", `<Project><ItemGroup><PackageReference Include="You.Lib" Version="2.0.0-edge.1" /></ItemGroup></Project>`)
	cache := stackReleaseFileWrite(t, member, "packages/restored/Restored.props", `<Project><ItemGroup><PackageReference Update="You.Lib" VersionOverride="1.0.0" /></ItemGroup></Project>`)
	for _, dir := range []string{"bin", "obj", ".vs", "node_modules"} {
		path := stackReleaseFileWrite(t, member, dir+"/Stale.props", `<Project><PackageReference Update="You.Lib" VersionOverride="1.0.0" /></Project>`)
		// Even tracked build output stays outside the release scope.
		mustGitStack(t, root, "add", "-f", "--", path)
	}
	edits, _, err := stackReleaseSelectedEdits(member, stackReleaseSelection{Reference: "You.Lib", Original: "Lib"}, "Lib", "2.0.0")
	if err != nil {
		t.Fatal(err)
	}
	if err = stackReleaseWrite(edits); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(cache)
	if err != nil || !bytes.Contains(data, []byte(`Update="You.Lib" VersionOverride="1.0.0"`)) {
		t.Fatalf("cache changed: %s %v", data, err)
	}
	ids, err := stackReleaseReferenceIDs(member, nil)
	if err != nil || slices.Contains(ids, "You.Lib") {
		t.Fatalf("cache counted: %v %v", ids, err)
	}
}

func TestStackReleasedCandidateFiles(t *testing.T) {
	for _, git := range []bool{false, true} {
		t.Run(map[bool]string{false: "snapshot", true: "git"}[git], func(t *testing.T) {
			root := stackReleaseFileFixture(t, git)
			member := filepath.Join(root, "member [one]")
			unusualName := "new line.props"
			// Windows forbids control characters in filenames.
			if runtime.GOOS != "windows" {
				unusualName = "new\nline.props"
			}
			for _, path := range []string{"packages/App/App.csproj", "generated/Defs.props", "vendor/Build.targets", "packages/App/Code.cs", unusualName} {
				stackReleaseFileWrite(t, member, path, "<Project />")
			}
			for _, dir := range []string{"bin", "obj", ".git", ".vs", "node_modules"} {
				stackReleaseFileWrite(t, member, dir+"/Skipped.csproj", "<Project />")
			}
			stackReleaseFileWrite(t, root, "Elsewhere.csproj", "<Project />")
			var files []string
			err := stackReleaseWalkFiles(member, func(path string) error {
				rel, err := filepath.Rel(member, path)
				if err != nil {
					return err
				}
				files = append(files, filepath.ToSlash(rel))
				return nil
			})
			if err != nil {
				t.Fatal(err)
			}
			want := []string{"generated/Defs.props", unusualName, "packages/App/App.csproj", "packages/App/Code.cs", "vendor/Build.targets"}
			if !slices.Equal(files, want) {
				t.Fatalf("files=%q want=%q", files, want)
			}
		})
	}
}

func TestStackReleasedCandidateSymlinks(t *testing.T) {
	for _, git := range []bool{false, true} {
		t.Run(map[bool]string{false: "snapshot", true: "git"}[git], func(t *testing.T) {
			root := stackReleaseFileFixture(t, git)
			target := stackReleaseFileWrite(t, root, "Target.xml", "<Project />")
			if err := os.Symlink(target, filepath.Join(root, "Link.props")); err != nil {
				t.Skipf("symlinks unavailable: %v", err)
			}
			if err := stackReleaseWalkFiles(root, func(string) error { return nil }); err == nil || !strings.Contains(err.Error(), "symlink") {
				t.Fatalf("symlink accepted: %v", err)
			}
		})
	}
}
