package secrets

import (
	"fmt"
	"sort"
	"strings"
)

// DopplerFetchAction is the fetch action the generated step uses, pinned by
// commit: a tag can be moved, and this step holds the repo's token.
const (
	DopplerFetchAction    = "dopplerhq/secrets-fetch-action"
	DopplerFetchActionSHA = "451892f16195f9ac360e1a5bcbf0b5fd0e957534"
	DopplerFetchActionTag = "v2.0.0"
)

// DefaultTokenSecret is the one GitHub Actions secret a repo holds: a
// read-only service token for its ci config.
const DefaultTokenSecret = "DOPPLER_TOKEN"

// CIOptions describes the steps a job needs to fetch its secrets.
type CIOptions struct {
	// Scope is the project/config the token must read; the generated guard
	// fails the job when the token reads anything else.
	Scope Scope
	// Names are the secrets the job's steps use. Each must be set and
	// non-empty, or the job fails before any step that would use it.
	Names []string
	// StepID is the fetch step's id (default DefaultStepID).
	StepID string
	// TokenSecret is the GitHub secret holding the token (default
	// DefaultTokenSecret).
	TokenSecret string
	// Indent is the column of the steps' leading "-" (default 6, a job's
	// `steps:` list in the usual layout).
	Indent int
}

// CIStepper is a Provider that can write the GitHub Actions steps fetching
// its secrets.
type CIStepper interface {
	CISteps(o CIOptions) (string, error)
}

// CISteps writes three steps: one that fails when the token secret is unset
// (the fetch action's own message names the input, not the secret to add);
// the pinned fetch, WITHOUT inject-env-vars, so no secret lands in the job's
// environment; and a guard that fails when the token reads another
// project/config or any named secret is missing or empty. The guard sees
// whether each secret is set, never its value. Each later step takes only
// what it needs: `env: NAME: ${{ steps.<id>.outputs.NAME }}`.
func (d *Doppler) CISteps(o CIOptions) (string, error) {
	o, names, err := o.normalized()
	if err != nil {
		return "", err
	}
	pad := strings.Repeat(" ", o.Indent)
	in := func(n int) string { return pad + strings.Repeat(" ", n) }
	var b strings.Builder
	line := func(indent int, format string, args ...any) {
		b.WriteString(in(indent))
		fmt.Fprintf(&b, format, args...)
		b.WriteByte('\n')
	}
	out := func(name string) string { return fmt.Sprintf("steps.%s.outputs.%s", o.StepID, name) }

	line(0, "# Generated by `rig secrets ci %s` — regenerate rather than edit.", strings.Join(names, " "))
	line(0, "# Steps take a secret with `env: NAME: ${{ %s }}`; never job-level env.", out("NAME"))
	line(0, "- name: Check the Doppler token")
	line(2, "shell: bash")
	line(2, "env:")
	line(4, "%s: ${{ secrets.%s }}", o.TokenSecret, o.TokenSecret)
	line(2, "run: |")
	line(4, `if [ -z "$%s" ]; then`, o.TokenSecret)
	line(6, `echo "::error::the %s secret is not set: add a read-only Doppler service token for %s as this repository's %s Actions secret"`, o.TokenSecret, o.Scope, o.TokenSecret)
	line(6, "exit 1")
	line(4, "fi")
	line(0, "- name: Fetch secrets from Doppler %s", o.Scope)
	line(2, "id: %s", o.StepID)
	line(2, "uses: %s@%s # %s", DopplerFetchAction, DopplerFetchActionSHA, DopplerFetchActionTag)
	line(2, "with:")
	line(4, "doppler-token: ${{ secrets.%s }}", o.TokenSecret)
	line(4, "doppler-project: %s", o.Scope.Project)
	line(4, "doppler-config: %s", o.Scope.Config)
	line(0, "- name: Require the secrets this job uses")
	line(2, "shell: bash")
	line(2, "env:")
	line(4, "DOPPLER_SCOPE: ${{ %s }}/${{ %s }}", out("DOPPLER_PROJECT"), out("DOPPLER_CONFIG"))
	for _, n := range names {
		line(4, "HAS_%s: ${{ %s != '' }}", n, out(n))
	}
	line(2, "run: |")
	line(4, `if [ "$DOPPLER_SCOPE" != "%s" ]; then`, o.Scope)
	line(6, `echo "::error::%s reads Doppler $DOPPLER_SCOPE, not %s"`, o.TokenSecret, o.Scope)
	line(6, "exit 1")
	line(4, "fi")
	line(4, `missing=""`)
	for _, n := range names {
		line(4, `[ "$HAS_%s" = true ] || missing="$missing %s"`, n, n)
	}
	line(4, `if [ -n "$missing" ]; then`)
	line(6, `echo "::error::missing or empty in Doppler %s:$missing"`, o.Scope)
	line(6, "exit 1")
	line(4, "fi")
	return b.String(), nil
}

// CIEnv is the `env:` block a consuming step adds for names, at indent (the
// column of the step's keys).
func CIEnv(stepID string, names []string, indent int) string {
	if stepID == "" {
		stepID = DefaultStepID
	}
	if indent < 0 {
		indent = 0
	}
	pad := strings.Repeat(" ", indent)
	var b strings.Builder
	b.WriteString(pad + "env:\n")
	for _, n := range names {
		fmt.Fprintf(&b, "%s  %s: ${{ steps.%s.outputs.%s }}\n", pad, n, stepID, n)
	}
	return b.String()
}

// DefaultIndent is the column of a job's `steps:` items in the usual layout.
const DefaultIndent = 6

// NormalizeIndent turns an unset or nonsensical indent into DefaultIndent, so
// the steps and the consuming step's env example line up with each other.
func NormalizeIndent(indent int) int {
	if indent <= 0 {
		return DefaultIndent
	}
	return indent
}

func (o CIOptions) normalized() (CIOptions, []string, error) {
	if o.StepID == "" {
		o.StepID = DefaultStepID
	}
	if o.TokenSecret == "" {
		o.TokenSecret = DefaultTokenSecret
	}
	o.Indent = NormalizeIndent(o.Indent)
	if !identifier.MatchString(o.Scope.Project) || !identifier.MatchString(o.Scope.Config) {
		return o, nil, fmt.Errorf("the project and config must be plain names, got %q", o.Scope.String())
	}
	if !ValidName(o.StepID) {
		return o, nil, fmt.Errorf("step id %q must be letters, digits and '_'", o.StepID)
	}
	if !ValidName(o.TokenSecret) {
		return o, nil, fmt.Errorf("token secret %q must be letters, digits and '_'", o.TokenSecret)
	}
	if len(o.Names) == 0 {
		return o, nil, fmt.Errorf("name the secrets the job uses — a fetch nothing reads is a token exposed for nothing")
	}
	seen := map[string]bool{}
	var names []string
	for _, n := range o.Names {
		n = strings.TrimSpace(n)
		if !ValidName(n) {
			return o, nil, fmt.Errorf("%q is not a secret name (letters, digits and '_')", n)
		}
		if !seen[n] {
			seen[n] = true
			names = append(names, n)
		}
	}
	sort.Strings(names)
	return o, names, nil
}
