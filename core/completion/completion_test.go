func TestZshScriptMatchesCobraWithoutBuildingCommands(t *testing.T) {
	for _, name := range []string{"rig", "shiprig", "changerig", "clauderig", "rig-dev"} {
		t.Run(name, func(t *testing.T) {
			var generated bytes.Buffer
			if err := (&cobra.Command{Use: name}).GenZshCompletion(&generated); err != nil {
				t.Fatal(err)
			}
			if got := ZshScript(name); got != generated.String() {
				t.Errorf("static zsh script differs from Cobra for %s", name)
			}
		})
	}
}

func TestZshScriptNormalizesCRLFTemplate(t *testing.T) {
	original := zshTemplate
	lfTemplate := strings.ReplaceAll(original, "\r\n", "\n")
	zshTemplate = strings.ReplaceAll(lfTemplate, "\n", "\r\n")
	t.Cleanup(func() { zshTemplate = original })

	var generated bytes.Buffer
	if err := (&cobra.Command{Use: "rig"}).GenZshCompletion(&generated); err != nil {
		t.Fatal(err)
	}
	if got := ZshScript("rig"); got != generated.String() {
		t.Fatal("CRLF template did not produce Cobra's zsh script")
	}
}

func TestZshRequestSkipsNormalStartup(t *testing.T) {
	var out bytes.Buffer
	err := Run([]string{"completion", "zsh"}, "rig", &out, func() error {
		t.Fatal("completion constructed the ordinary CLI")
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(out.String(), "#compdef rig\n") {
		t.Fatalf("unexpected completion output: %q", out.String()[:min(out.Len(), 100)])
	}
}

func TestInstallAutoloadFileAndRefreshOnBinaryChange(t *testing.T) {
	dataHome := t.TempDir()
	t.Setenv("XDG_DATA_HOME", dataHome)
	bin := filepath.Join(t.TempDir(), "rig")
	if err := os.WriteFile(bin, []byte("version one"), 0o755); err != nil {
		t.Fatal(err)
	}
	path, changed, err := Install("rig-dev", bin, "")
	if err != nil || !changed {
		t.Fatalf("first install: changed=%v err=%v", changed, err)
	}
	want := filepath.Join(dataHome, "rigsmith", "zsh", "site-functions", "_rig-dev")
	if path != want {
		t.Fatalf("path = %q, want %q", path, want)
	}
	first, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.HasPrefix(first, []byte("#compdef rig-dev\n")) || !bytes.Contains(first, []byte("_rig-dev()")) {
		t.Fatalf("installed file is not an autoloadable rig-dev script")
	}
	if _, changed, err := Install("rig-dev", bin, ""); err != nil || changed {
		t.Fatalf("same binary should not rewrite: changed=%v err=%v", changed, err)
	}
	if err := os.WriteFile(bin, []byte("version two"), 0o755); err != nil {
		t.Fatal(err)
	}
	if _, changed, err := Install("rig-dev", bin, ""); err != nil || !changed {
		t.Fatalf("changed binary should refresh: changed=%v err=%v", changed, err)
	}
	second, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Equal(first, second) {
		t.Fatal("binary fingerprint did not change")
	}
}
